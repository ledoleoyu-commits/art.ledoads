const activeLanguage = new URLSearchParams(window.location.search).get("lang") === "en" ? "en" : "ja";
const copy = translations[activeLanguage];
document.documentElement.lang = activeLanguage;
document.title = copy.pageTitle;
document.querySelectorAll("[data-i18n]").forEach((element) => {
  const key = element.dataset.i18n;
  if (copy[key]) element.textContent = copy[key];
});
document.querySelectorAll("[data-i18n-html]").forEach((element) => {
  const key = element.dataset.i18nHtml;
  if (copy[key]) element.innerHTML = copy[key];
});
document.querySelectorAll("[data-lang-link]").forEach((link) => {
  if (link.dataset.langLink === activeLanguage) {
    link.classList.add("active");
    link.setAttribute("aria-current", "page");
  }
});
document.querySelectorAll(".project-card").forEach((card) => {
  const title = card.querySelector("h3").textContent;
  card.querySelector(".project-image").setAttribute("aria-label", `${activeLanguage === "en" ? "View" : "画像を見る"} ${title}`);
});

const lightbox = document.querySelector(".lightbox");
const lightboxImage = lightbox.querySelector("img");
const lightboxCaption = lightbox.querySelector("p");

document.querySelectorAll(".project-image").forEach((button) => {
  button.addEventListener("click", () => {
    const image = button.querySelector("img");
    const title = button.closest(".project-card").querySelector("h3").textContent;
    lightboxImage.src = image.src;
    lightboxImage.alt = image.alt;
    lightboxCaption.textContent = title;
    lightbox.showModal();
  });
});

lightbox.querySelector(".lightbox-close").addEventListener("click", () => lightbox.close());
lightbox.addEventListener("click", (event) => {
  if (event.target === lightbox) lightbox.close();
});

document.querySelector(".contact-form").addEventListener("submit", async (event) => {
  event.preventDefault();
  const form = event.currentTarget;
  const status = form.querySelector(".form-status");
  const button = form.querySelector('button[type="submit"]');
  const values = new FormData(form);
  const countryCode = values.get("countryCode");
  const phone = String(values.get("phone") || "").trim();
  const payload = {
    surname: String(values.get("surname") || "").trim(),
    firstName: String(values.get("firstName") || "").trim(),
    email: String(values.get("email") || "").trim(),
    phone: phone ? `${countryCode} ${phone}` : "",
    address: String(values.get("address") || "").trim(),
    company: String(values.get("company") || "").trim()
  };

  status.textContent = copy.formSending;
  button.disabled = true;
  button.textContent = copy.formSending;

  try {
    const response = await fetch("https://mailbox-service-zduur442vq-df.a.run.app/api/contact", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify(payload)
    });
    const result = await response.json();
    if (!response.ok || !result.success) throw new Error("Contact form request failed");
    status.textContent = copy.formSuccess;
    form.reset();
  } catch {
    status.textContent = copy.formError;
  } finally {
    button.disabled = false;
    button.textContent = copy.sendLabel;
  }
});
